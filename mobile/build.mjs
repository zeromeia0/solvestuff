// Builds the Android APK: copies ../public into www/, points it at the server,
// stamps the build number, then runs Capacitor + Gradle.
//
//   make apk                         (from the repo root)
//   SERVER=https://example.com make apk
//
// Output: dist/solvestuff-<versionName>-build<versionCode>.apk. Upload it in
// the teacher area (App Android) and installed apps will offer the update.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync, rmSync, cpSync, mkdirSync, copyFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const at = (...p) => path.join(here, ...p);
const toolchain = path.join(os.homedir(), '.local/share/android-toolchain');
const env = {
  ...process.env,
  JAVA_HOME: process.env.JAVA_HOME || path.join(toolchain, 'jdk'),
  ANDROID_HOME: process.env.ANDROID_HOME || path.join(toolchain, 'sdk'),
};
const run = (cmd, args, cwd = here) => execFileSync(cmd, args, { cwd, env, stdio: 'inherit' });

// app.json holds the server address and the last build number (committed, so it never goes backwards).
const app = JSON.parse(readFileSync(at('app.json'), 'utf8'));
const server = (process.env.SERVER || app.server).replace(/\/$/, '');
if (!/^https?:\/\//.test(server)) throw new Error(`SERVER must start with http:// or https:// (got "${server}")`);
const versionCode = app.versionCode + 1;
const versionName = JSON.parse(readFileSync(at('..', 'package.json'), 'utf8')).version;
const plainHttp = server.startsWith('http://');

if (!existsSync(at('node_modules'))) run('pnpm', ['install']);

// 1. Web assets.
rmSync(at('www'), { recursive: true, force: true });
cpSync(at('..', 'public'), at('www'), { recursive: true });
writeFileSync(
  at('www', 'js', 'config.js'),
  `// Generated by mobile/build.mjs\nwindow.SOLVESTUFF_API_BASE = ${JSON.stringify(server)};\nwindow.SOLVESTUFF_APP_BUILD = ${versionCode};\n`,
);

// 2. Capacitor config. The app id must never change, or phones treat it as a different app.
writeFileSync(
  at('capacitor.config.json'),
  JSON.stringify(
    {
      appId: 'io.github.zeromeia0.solvestuff',
      appName: 'solvestuff',
      webDir: 'www',
      // A plain-http server (e.g. on the local network while testing) needs cleartext + mixed content.
      server: { androidScheme: 'https', cleartext: plainHttp },
      android: { allowMixedContent: plainHttp },
    },
    null,
    2,
  ),
);

// 3. Signing key. Every update must be signed with the same key, so back up
//    release.keystore + keystore.properties somewhere safe (they're not in git).
if (!existsSync(at('release.keystore'))) {
  const password = randomBytes(18).toString('base64url');
  run(path.join(env.JAVA_HOME, 'bin', 'keytool'), [
    '-genkeypair', '-noprompt', '-keystore', at('release.keystore'), '-alias', 'solvestuff',
    '-keyalg', 'RSA', '-keysize', '4096', '-validity', '36500',
    '-storepass', password, '-keypass', password, '-dname', 'CN=solvestuff',
  ]);
  writeFileSync(
    at('keystore.properties'),
    `storeFile=${at('release.keystore')}\nstorePassword=${password}\nkeyAlias=solvestuff\nkeyPassword=${password}\n`,
  );
}

// 4. Native project + build.
const cap = at('node_modules', '.bin', 'cap');
if (!existsSync(at('android'))) run(cap, ['add', 'android']);
run(cap, ['sync', 'android']);
run('./gradlew', ['assembleRelease', '--quiet', `-PappVersionCode=${versionCode}`, `-PappVersionName=${versionName}`], at('android'));

mkdirSync(at('dist'), { recursive: true });
const out = at('dist', `solvestuff-${versionName}-build${versionCode}.apk`);
copyFileSync(at('android', 'app', 'build', 'outputs', 'apk', 'release', 'app-release.apk'), out);
writeFileSync(at('app.json'), `${JSON.stringify({ ...app, versionCode }, null, 2)}\n`);

console.log(`\nAPK: ${path.relative(process.cwd(), out)}  (version ${versionName}, build ${versionCode}, server ${server})`);
